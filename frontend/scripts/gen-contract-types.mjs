// Generates src/contracts/types.ts from the exported ABIs so contract calls are
// type-checked without pulling in TypeChain. Run after `npm run compile` at the root.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const abiDir = join(root, "src/contracts/abi");
const out = join(root, "src/contracts/types.ts");

const structs = new Map();

function structName(param) {
  const m = /struct\s+(?:\w+\.)?(\w+)/.exec(param.internalType ?? "");
  return m ? m[1] : null;
}

function enumName(param) {
  const m = /enum\s+(?:\w+\.)?(\w+)/.exec(param.internalType ?? "");
  return m ? m[1] : null;
}

function tsType(param, dir) {
  const arr = /^(.*)\[(\d*)\]$/.exec(param.type);
  if (arr) {
    const inner = { ...param, type: arr[1], internalType: (param.internalType ?? "").replace(/\[\d*\]$/, "") };
    return `${tsType(inner, dir)}[]`;
  }
  if (param.type === "tuple") {
    const name = structName(param);
    if (name && !structs.has(name)) structs.set(name, param.components);
    return name ? (dir === "in" ? `${name}Input` : name) : "unknown";
  }
  if (/^u?int/.test(param.type)) {
    if (dir === "out" && enumName(param)) return "bigint";
    return dir === "in" ? "BigNumberish" : "bigint";
  }
  if (param.type === "address") return dir === "in" ? "AddressLike" : "string";
  if (param.type === "bool") return "boolean";
  if (param.type === "string") return "string";
  if (param.type.startsWith("bytes")) return dir === "in" ? "BytesLike" : "string";
  return "unknown";
}

function fnSignature(fn) {
  const args = fn.inputs.map((p, i) => `${p.name || `arg${i}`}: ${tsType(p, "in")}`);
  const view = fn.stateMutability === "view" || fn.stateMutability === "pure";
  let ret;
  if (!view) ret = "ContractTransactionResponse";
  else if (fn.outputs.length === 0) ret = "void";
  else if (fn.outputs.length === 1) ret = tsType(fn.outputs[0], "out");
  else ret = `[${fn.outputs.map((o) => tsType(o, "out")).join(", ")}]`;
  if (!view) args.push("overrides?: Overrides");
  return `  ${fn.name}: Method<[${args.join(", ")}], ${ret}>;`;
}

const blocks = [];
for (const file of readdirSync(abiDir).filter((f) => f.endsWith(".json")).sort()) {
  const name = file.replace(/\.json$/, "");
  const abi = JSON.parse(readFileSync(join(abiDir, file), "utf8"));
  const fns = abi.filter((e) => e.type === "function");
  const seen = new Set();
  const lines = [];
  for (const fn of fns) {
    if (seen.has(fn.name)) continue;
    seen.add(fn.name);
    lines.push(fnSignature(fn));
  }
  blocks.push(`export interface ${name}Contract extends BaseContract {\n${lines.join("\n")}\n}`);
}

const structBlocks = [];
for (const [name, comps] of structs) {
  const outFields = comps.map((c) => `  ${c.name}: ${tsType(c, "out")};`).join("\n");
  const inFields = comps.map((c) => `  ${c.name}: ${tsType(c, "in")};`).join("\n");
  structBlocks.push(`export interface ${name} {\n${outFields}\n}`);
  structBlocks.push(`export interface ${name}Input {\n${inFields}\n}`);
}

const header = `// Generated by scripts/gen-contract-types.mjs. Do not edit by hand.
import type {
  AddressLike,
  BaseContract,
  BigNumberish,
  BytesLike,
  ContractTransactionResponse,
  Overrides,
} from "ethers";

export interface Method<A extends unknown[], R> {
  (...args: A): Promise<R>;
  staticCall(...args: A): Promise<R extends ContractTransactionResponse ? unknown : R>;
  estimateGas(...args: A): Promise<bigint>;
}
`;

writeFileSync(out, [header.trimEnd(), ...structBlocks, ...blocks].join("\n\n") + "\n");
console.log(`Wrote ${out}`);
